# build_dev.ps1 - builds Trinity with the developer probe into Trinity\build-dev (no packaging, no deploy).
param([switch]$Deploy)
$ErrorActionPreference = 'Stop'
$source = Split-Path $PSScriptRoot -Parent
$build  = Join-Path $source 'build-dev'
$vs     = 'C:\Program Files (x86)\Microsoft Visual Studio\18\BuildTools'
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat'
$ninja  = Join-Path $vs 'Common7\IDE\CommonExtensions\Microsoft\CMake\Ninja\ninja.exe'
$env:PATH = (Join-Path $vs 'Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin') + ';' + $env:PATH

$stamp = (Get-Date).ToString('MMM d yyyy HH:mm:ss', [Globalization.CultureInfo]::InvariantCulture)
@"
// AUTO-GENERATED by Build_Trinity.ps1 - do not edit. Refreshed every build.
#pragma once
#define TRINITY_BUILD_TIME "$stamp"
"@ | Set-Content -LiteralPath (Join-Path $source 'src\core\build_timestamp.h') -Encoding ASCII

$configure = '"{0}" >nul && cmake.exe -S "{1}" -B "{2}" -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_MAKE_PROGRAM="{3}" -DENABLE_DEVPROBE=ON' -f $vcvars, $source, $build, $ninja
& cmd.exe /d /s /c $configure
if ($LASTEXITCODE -ne 0) { throw "configure failed ($LASTEXITCODE)" }
& cmd.exe /d /s /c ('"{0}" >nul && cmake.exe --build "{1}" --target Trinity' -f $vcvars, $build)
if ($LASTEXITCODE -ne 0) { throw "build failed ($LASTEXITCODE)" }
$asi = Join-Path $build 'Trinity.asi'
Write-Host "built: $asi  $((Get-FileHash $asi -Algorithm SHA256).Hash)"

if ($Deploy) {
    $bin = 'C:\Program Files (x86)\Steam\steamapps\common\Crimson Desert\bin64'
    if (Get-Process CrimsonDesert -ErrorAction SilentlyContinue) { throw 'game is running; close it before deploying' }
    Copy-Item $asi (Join-Path $bin 'Trinity.asi') -Force
    $loader = Join-Path $bin 'winmm.dll'
    if (-not (Test-Path $loader)) {
        Write-Warning 'no ASI loader (winmm.dll) in bin64 - install one before launching'
    }
    Write-Host "deployed to $bin"
}

