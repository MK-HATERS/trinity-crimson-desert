# gen_character_names.py - builds src/game/character_names.h (character key -> English display name).
# Source data: NattKh/CRIMSON-DESERT-SAVE-EDITOR-AND-GAME-MODS, CrimsonGameMods/data/character_catalog.json
# (MPL-2.0). The generated header carries the same license notice and stays a separate file.
import json, sys, pathlib

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
rows = json.loads(src.read_text(encoding="utf-8"))["characters"]

names = {}
for r in rows:
    name = (r.get("display_name") or "").strip()
    if name and r["character_key"] not in names:
        names[r["character_key"]] = name


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "// AUTO-GENERATED by scripts/gen_character_names.py - do not edit.",
    "// Character key -> English display name.",
    "// Data: NattKh/CRIMSON-DESERT-SAVE-EDITOR-AND-GAME-MODS character_catalog.json,",
    "// Copyright (c) 2026 RicePaddySoftware, Mozilla Public License 2.0",
    "// (https://mozilla.org/MPL/2.0/). This file is covered by the MPL-2.0.",
    "#pragma once",
    "#include <cstdint>",
    "",
    "namespace trinity::game::character_names",
    "{",
    "    struct Entry { uint32_t key; const char* name; };",
    "    inline constexpr Entry kNames[] = {",
]
for k in sorted(names):
    lines.append(f"        {{ {k}u, {c_str(names[k])} }},")
lines += ["    };", f"    inline constexpr unsigned kCount = {len(names)};", "}", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(names)} names -> {out}")
