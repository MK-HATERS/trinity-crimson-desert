# gen_knowledge_names.py - builds src/game/knowledge_names.h (knowledge key -> English display name).
# Source data: NattKh/CRIMSON-DESERT-SAVE-EDITOR-AND-GAME-MODS, CrimsonGameMods/data/knowledge_keys_all.json
# (MPL-2.0). The generated header carries the same license notice and stays a separate file.
import json, sys, pathlib

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
rows = json.loads(src.read_text(encoding="utf-8"))

seen = {}
for r in rows:
    name = (r.get("display_name") or "").strip()
    if name and r["key"] not in seen:
        seen[r["key"]] = name


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "// AUTO-GENERATED by scripts/gen_knowledge_names.py - do not edit.",
    "// Knowledge key -> English display name.",
    "// Data: NattKh/CRIMSON-DESERT-SAVE-EDITOR-AND-GAME-MODS knowledge_keys_all.json,",
    "// Copyright (c) 2026 RicePaddySoftware, Mozilla Public License 2.0",
    "// (https://mozilla.org/MPL/2.0/). This file is covered by the MPL-2.0.",
    "#pragma once",
    "#include <cstdint>",
    "",
    "namespace trinity::game::knowledge_names",
    "{",
    "    struct Entry { uint32_t key; const char* name; };",
    f"    inline constexpr Entry kNames[] = {{",
]
for k in sorted(seen):
    lines.append(f"        {{ {k}u, {c_str(seen[k])} }},")
lines += [
    "    };",
    f"    inline constexpr unsigned kCount = {len(seen)};",
    "}",
    "",
]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(seen)} names -> {out}")
